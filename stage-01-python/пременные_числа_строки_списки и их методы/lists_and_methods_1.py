x = [34, 23, 12, 15, 12]
print(x)
x.append('Bob') # добавление одного элм к списку в конце  >> [34, 23, 12, 15, 12, 'Bob']
print(x)
# x = x.append(7) # response >> None. В списках НИКОГДА не использовать ПРИСВОЕНИЕ! это ПОТЕРЯ списка!

# x.clear()  #  очистка списка
# print(x)

z = x.copy() # Копия. Будет два отдельный списка Z и X

print(z.count(12)) # сколько раз встретилось это число в списке   >> 2

print(z.index(15)) # метод возвращает индекс числа  >> 3

x.insert(0, '00.751') # (индекс, что вставить) >> ['00.751', 34, 23, 12, 15, 12, 'Bob']
print(x)

popz = x.pop() # сохранили в переменную, то что удалил метод pop() с конца списка. Удалил Bob
print(popz) # >> Bob
print(x)  # >> ['00.751', 34, 23, 12, 15, 12]
popt = x.pop(0) # удаление через pop() ПО ИНДЕКСУ!!!
print(popt) # >> 00.751
print(x) # >> [34, 23, 12, 15, 12] 

print(z)  # >> [34, 23, 12, 15, 12, 'Bob']
z.remove(34) # удаляет по ЗНАЧЕНИЮ >> 34
print(z) # >> [23, 12, 15, 12, 'Bob']

print(z)  # >> [23, 12, 15, 12, 'Bob']
z.reverse()  # переварачивает список
print(z)  # >> ['Bob', 12, 15, 12, 23]
z.pop(0)

print(z)  # >> [12, 15, 12, 23]
z.sort()  # сортирует список
print(z)  # >> [12, 12, 15, 23]
z.sort(reverse=True) # сортируется по убыванию
print(z)  # >> [23, 15, 12, 12]
